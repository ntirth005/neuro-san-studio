"""
Generate the additive synthetic datasets used by the extended inventory operations network.

The generator is deterministic and only writes files that are not part of the original
38-question baseline. Run from the repository root:

    python scripts/generate_extended_inventory_data.py
"""

import csv
import datetime
import json
import os
import random
from typing import Dict
from typing import List

STORE_ID = "demo-store"
DATA_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "data"))
REFERENCE_DATE = datetime.date(2026, 10, 17)


def write_csv(filename: str, fieldnames: List[str], rows: List[Dict[str, object]]) -> None:
    """Write a deterministic CSV file."""
    path = os.path.join(DATA_DIR, filename)
    with open(path, mode="w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {filename}: {len(rows)} rows")


def generate_location_demand() -> None:
    """Create 90 days of location-level demand consistent with the aggregate velocity."""
    base_rates = {
        "WH-01": {"SKU-001": 2.5, "SKU-002": 1.2, "SKU-003": 0.45, "SKU-004": 0.08, "SKU-005": 0.7, "SKU-006": 0.0},
        "WH-02": {"SKU-001": 1.3, "SKU-002": 0.2, "SKU-003": 0.1, "SKU-004": 0.02, "SKU-005": 0.2, "SKU-006": 0.0},
        "WH-03": {"SKU-001": 0.6, "SKU-002": 0.1, "SKU-003": 0.06, "SKU-004": 0.01, "SKU-005": 0.06, "SKU-006": 0.0},
    }
    location_meta = {
        "WH-01": ("warehouse", "North"),
        "WH-02": ("warehouse", "West"),
        "WH-03": ("marketplace", "South"),
    }
    weekday_factors = {
        "Monday": 1.0,
        "Tuesday": 1.0,
        "Wednesday": 1.0,
        "Thursday": 1.0,
        "Friday": 1.15,
        "Saturday": 1.25,
        "Sunday": 1.1,
    }
    rng = random.Random(42)
    rows = []
    start = REFERENCE_DATE - datetime.timedelta(days=90)
    for day_offset in range(90):
        day = start + datetime.timedelta(days=day_offset)
        factor = weekday_factors[day.strftime("%A")]
        for location_id, skus in base_rates.items():
            channel, region = location_meta[location_id]
            for sku, rate in skus.items():
                expected = rate * factor * rng.uniform(0.85, 1.15)
                units = int(expected) + (1 if rng.random() < (expected - int(expected)) else 0)
                rows.append(
                    {
                        "store_id": STORE_ID,
                        "date": day.isoformat(),
                        "location_id": location_id,
                        "sku": sku,
                        "units": units,
                        "channel": channel,
                        "region": region,
                    }
                )
    write_csv(
        "location_demand.csv",
        [
            "store_id",
            "date",
            "location_id",
            "sku",
            "units",
            "channel",
            "region",
        ],
        rows,
    )


